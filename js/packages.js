// The reveals come FIRST because PACKAGES names structureReveal while it loads (arc III's `reveal:`); in one
// script a function further down was hoisted, but a function in a later file does not exist yet.
// ---- surprise reveals ("wait, I made THAT?") — one per arc, fired after the power card is claimed ----
let pendingReveal=null, revealHarm=false, revealSync=false, revealRestore=null;
// replay the player's own creation, briefly enhanced (harmony line / jam backing / whole-garden sync)
function runReveal(o){
  if(playing) stop();
  const wasLoop=looping, wasJam=jamMode;
  revealHarm=!!o.harm; revealSync=!!o.sync;
  if(o.jam && !jamMode){ jamMode=true; jamBtn.classList.add("on"); applyGrooveTempo(); }
  looping=false; loopBtn.classList.remove("on");
  revealRestore=()=>{ revealHarm=revealSync=false; revealRestore=null;
    if(o.jam && !wasJam){ jamMode=false; jamBtn.classList.remove("on"); }
    looping=wasLoop; loopBtn.classList.toggle("on",wasLoop);
    settle(); toast("🤩 You made that!"); };
  setStatus(o.msg); toast(o.msg);
  start();
}
// arc III: the player's first Tower rises as a real structure — arpeggio up, then it stands as one
function structureReveal(){
  const tower=toolbox.find(isTowerTool); if(!tower) return;
  initAudio(); actx.resume(); const t0=actx.currentTime+0.15;
  tower.midis.forEach((m,i)=>voice(instrEl.value, midiToFreq(m), t0+i*0.28));        // rises…
  const tb=tower.midis.length*0.28+0.45;
  tower.midis.forEach(m=>voice(instrEl.value, midiToFreq(m), t0+tb));                // …then stands as one
  setStatus("✨ Your chord rises — a structure strong enough to stand!");
  bigRise("🏛️", tower.midis.length*0.28*1000);
  setTimeout(()=>{ settle(); toast("🤩 You built that!"); }, (tb+0.3)*1000);
}
