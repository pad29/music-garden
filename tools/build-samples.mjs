#!/usr/bin/env node
// Pack instrument sample mp3s into a script-tag-loadable JS file (samples/<instr>.js).
// Why not fetch the mp3s directly? The game must work when index.html is opened via file://
// (double-click), and browsers block fetch/XHR there — but <script src> loads fine.
// Run from the repo root: node tools/build-samples.mjs
import fs from "node:fs";
import path from "node:path";

const INSTRUMENTS = {
  // Salamander Grand Piano by Alexander Holm (CC-BY), via tonejs.github.io/audio/salamander/
  piano: { dir: "samples/piano",
    notes: { 60:"C4", 63:"Ds4", 66:"Fs4", 69:"A4", 72:"C5", 75:"Ds5", 78:"Fs5", 81:"A5", 84:"C6" } },
};

for (const [instr, spec] of Object.entries(INSTRUMENTS)) {
  const entries = Object.entries(spec.notes).map(([midi, name]) => {
    const b64 = fs.readFileSync(path.join(spec.dir, name + ".mp3")).toString("base64");
    return ` "${midi}":"${b64}"`;
  });
  const out = `// generated by tools/build-samples.mjs — do not edit by hand\n` +
    `window.SAMPLE_DATA=window.SAMPLE_DATA||{};\n` +
    `SAMPLE_DATA.${instr}={\n` + entries.join(",\n") + `\n};\n`;
  const file = `samples/${instr}.js`;
  fs.writeFileSync(file, out);
  console.log(`${file}: ${Object.keys(spec.notes).length} notes, ${(fs.statSync(file).size/1024).toFixed(0)} KB`);
}
